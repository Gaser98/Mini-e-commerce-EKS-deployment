func TestIntegration_CreateAndListOrders(t *testing.T) {
	conn := openTestDB(t)
	truncateAll(t, conn)
	seedUser(t, conn, "carol@example.com", "pass")

	router := integrationRouter(conn)
	token := loginToken(t, router, "carol@example.com", "pass")

	// Create
	body, _ := json.Marshal(map[string]float64{"total": 25.00})
	w := httptest.NewRecorder()
	r, _ := http.NewRequest(http.MethodPost, "/orders", bytes.NewReader(body))
	r.Header.Set("Content-Type", "application/json")
	r.Header.Set("Authorization", token)
	router.ServeHTTP(w, r)

	if w.Code != http.StatusCreated {
		t.Fatalf("POST /orders: expected 201, got %d: %s", w.Code, w.Body.String())
	}

	// List
	w = httptest.NewRecorder()
	r, _ = http.NewRequest(http.MethodGet, "/orders", nil)
	r.Header.Set("Authorization", token)
	router.ServeHTTP(w, r)

	if w.Code != http.StatusOK {
		t.Fatalf("GET /orders: expected 200, got %d", w.Code)
	}
	var orders []map[string]interface{}
	json.NewDecoder(w.Body).Decode(&orders)
	if len(orders) != 1 {
		t.Fatalf("expected 1 order, got %d", len(orders))
	}
}
