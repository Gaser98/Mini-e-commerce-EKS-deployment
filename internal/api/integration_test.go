//go:build integration

// Integration tests run against a real PostgreSQL instance.
// They are excluded from normal "go test ./..." runs. Run them explicitly:
//
//	go test -tags=integration ./internal/api/ -v
//
// In CI, GitHub Actions provides a postgres service container and sets
// TEST_DATABASE_URL before this job runs.

package api_test

