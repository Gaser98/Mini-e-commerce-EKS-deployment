func TestIntegration_LoginAndGetMe(t *testing.T) {
	conn := openTestDB(t)
	truncateAll(t, conn)
	seedUser(t, conn, "alice@example.com", "password123")

	router := integrationRouter(conn)
	token := loginToken(t, router, "alice@example.com", "password123")

	w := httptest.NewRecorder()
	r, _ := http.NewRequest(http.MethodGet, "/users/me", nil)
	r.Header.Set("Authorization", token)
	router.ServeHTTP(w, r)

	if w.Code != http.StatusOK {
		t.Fatalf("GET /users/me: expected 200, got %d: %s", w.Code, w.Body.String())
	}
}

